-- 사용자별 복약 일정. owner_uid는 Firebase 사용자 ID이고, 로그인 확인을 끈 개발 환경에서는 'local'이다.
-- H2(PostgreSQL 모드)와 PostgreSQL에서 똑같이 동작하는 문법만 쓴다.
CREATE TABLE medication_plans (
  id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_uid            VARCHAR(128) NOT NULL,
  item_seq             VARCHAR(30),
  custom_name          VARCHAR(50),
  item_name            VARCHAR(400) NOT NULL,
  item_image_url       VARCHAR(500),
  nickname             VARCHAR(30),
  dosage_amount        DOUBLE PRECISION NOT NULL,
  dosage_unit          VARCHAR(10) NOT NULL,
  frequency_type       VARCHAR(15) NOT NULL,
  interval_days        INT,
  days_of_week         VARCHAR(30),
  time_slots_json      VARCHAR(1000) NOT NULL,
  meal_relation        VARCHAR(15),
  meal_offset_minutes  INT,
  start_date           DATE NOT NULL,
  end_date             DATE,
  remaining_quantity   DOUBLE PRECISION,
  notification_enabled BOOLEAN NOT NULL,
  memo                 VARCHAR(200),
  status               VARCHAR(10) NOT NULL,
  source_job_id        VARCHAR(40),
  created_at           TIMESTAMP WITH TIME ZONE NOT NULL,
  updated_at           TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX medication_plans_owner ON medication_plans (owner_uid, status, id);
